// Regenerates shared/discord-defaults.ts from Valenced-Theme-Keys' resolved colours.
// usage: node scripts/theme-defaults.mjs [path/to/Valenced-Theme-Keys/data/resolved.json]
import { readFileSync, writeFileSync } from 'node:fs'

const source = process.argv[2] ?? '../Valenced-Theme-Keys/data/resolved.json'
const { discord, semantic } = JSON.parse(readFileSync(source, 'utf8'))

function table(base) {
	const lines = Object.keys(semantic)
		.sort()
		.map(key => `\t${key}: '${semantic[key][base]}',`)
	return `{\n${lines.join('\n')}\n}`
}

writeFileSync(
	'shared/discord-defaults.ts',
	`// Generated by scripts/theme-defaults.mjs from Discord ${discord}. Do not edit.

/** Discord's semantic colours on Ash, which dark themes map from. */
export const AshColors: Record<string, string> = ${table('dark')}

/** Discord's semantic colours on Light, which light themes map from. */
export const LightColors: Record<string, string> = ${table('light')}
`,
)
console.log(
	`Wrote ${Object.keys(semantic).length} keys from Discord ${discord}`,
)
